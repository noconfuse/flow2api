    # ========== 辅助方法 ==========

    async def _handle_retryable_generation_error(
        self,
        error: Exception,
        retry_attempt: int,
        max_retries: int,
        browser_id: Optional[Union[int, str]],
        project_id: str,
        log_prefix: str,
    ) -> bool:
        """统一处理生成链路的重试判定与打码自愈通知。"""
        error_str = str(error)
        terminal_reason = self._get_terminal_generation_rejection_reason(error_str)
        retry_reason = self._get_retry_reason(error_str)
        notify_reason = terminal_reason or retry_reason or error_str[:120] or type(error).__name__
        await self._notify_browser_captcha_error(
            browser_id=browser_id,
            project_id=project_id,
            error_reason=notify_reason,
            error_message=error_str,
        )
        if terminal_reason:
            debug_logger.log_warning(
                f"{log_prefix}遇到终态上游拒绝（{terminal_reason}），不执行自动重试。"
            )
            return False
        if not retry_reason:
            return False

        is_terminal_attempt = retry_attempt >= max_retries - 1

        if is_terminal_attempt:
            debug_logger.log_warning(
                f"{log_prefix}遇到{retry_reason}，已达到最大重试次数({max_retries})，本次请求失败并执行关闭回收。"
            )
            return False

        debug_logger.log_warning(
            f"{log_prefix}遇到{retry_reason}，正在重新获取验证码重试 ({retry_attempt + 2}/{max_retries})..."
        )
        await asyncio.sleep(1)
        return True

    async def _handle_missing_recaptcha_token(
        self,
        retry_attempt: int,
        max_retries: int,
        browser_id: Optional[Union[int, str]],
        project_id: str,
        log_prefix: str,
    ) -> bool:
        token_error = Exception("Failed to obtain reCAPTCHA token")
        return await self._handle_retryable_generation_error(
            error=token_error,
            retry_attempt=retry_attempt,
            max_retries=max_retries,
            browser_id=browser_id,
            project_id=project_id,
            log_prefix=log_prefix,
        )

    def _prefer_existing_generation_error(
        self,
        existing_error: Optional[Exception],
        fallback_message: str = "Failed to obtain reCAPTCHA token",
    ) -> Exception:
        """保留更早出现的真实上游错误，避免被后续的 token 获取失败覆盖。"""
        if existing_error:
            existing_text = str(existing_error or "").strip().lower()
            fallback_text = fallback_message.strip().lower()
            if existing_text and existing_text != fallback_text:
                return existing_error
        return Exception(fallback_message)

    def _get_terminal_generation_rejection_reason(self, error_str: str) -> Optional[str]:
        """识别不应继续自动重试的终态上游拒绝。"""
        error_lower = str(error_str or "").lower()
        if not error_lower:
            return None

        if "public_error_unusual_activity_too_much_traffic" in error_lower:
            return "异常活动/流量过高"
        if (
            "public_error_unusual_activity" in error_lower
            and "recaptcha evaluation failed" in error_lower
        ):
            return "异常活动/reCAPTCHA 拒绝"
        if (
            "resource_exhausted" in error_lower
            and "recaptcha evaluation failed" in error_lower
        ):
            return "RESOURCE_EXHAUSTED/reCAPTCHA 拒绝"
        return None

    def _get_retry_reason(self, error_str: str) -> Optional[str]:
        """判断是否需要重试，返回日志提示内容"""
        error_lower = error_str.lower()
        if "403" in error_lower:
            return "403错误"
        if "429" in error_lower or "too many requests" in error_lower:
            return "429限流"
        if any(keyword in error_lower for keyword in [
            "502",
            "503",
            "504",
            "bad gateway",
            "service unavailable",
            "gateway timeout",
        ]):
            return "5xx暂时不可用"
        if self._is_retryable_network_error(error_str):
            return "网络/TLS错误"
        if "recaptcha evaluation failed" in error_lower:
            return "reCAPTCHA 验证失败"
        if "recaptcha" in error_lower:
            return "reCAPTCHA 错误"
        if any(keyword in error_lower for keyword in [
            "http error 500",
            "public_error",
            "internal error",
            "reason=internal",
            "reason: internal",
            "\"reason\":\"internal\"",
            "server error",
            "upstream error",
        ]):
            return "500/内部错误"
        return None

