    def _parse_sortable_timestamp(self, raw_value: Any) -> Optional[datetime]:
        text = str(raw_value or "").strip()
        if not text:
            return None
        normalized = text.replace("Z", "+00:00")
        try:
            parsed = datetime.fromisoformat(normalized)
        except ValueError:
            return None
        if parsed.tzinfo is None:
            return parsed.replace(tzinfo=timezone.utc)
        return parsed.astimezone(timezone.utc)

    def _sort_project_media_for_ui_order(self, items: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """尽量贴近官网素材列表顺序：按最新时间倒序，保持同时间下的稳定顺序。"""
        indexed_items = list(enumerate(items))

        def sort_key(entry: tuple[int, Dict[str, Any]]) -> tuple[int, float, int]:
            original_index, item = entry
            sort_dt = self._parse_sortable_timestamp(item.get("update_time")) or self._parse_sortable_timestamp(
                item.get("create_time")
            )
            if sort_dt is None:
                return (1, 0.0, original_index)
            return (0, -sort_dt.timestamp(), original_index)

        return [item for _, item in sorted(indexed_items, key=sort_key)]

