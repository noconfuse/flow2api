    async def resolve_media_redirect_url(
        self,
        st: str,
        media_name: str,
        project_id: Optional[str] = None,
    ) -> str:
        """解析媒体重定向地址，返回最终可访问的签名 URL。"""
        clean_media_name = str(media_name or "").strip()
        if not clean_media_name:
            raise ValueError("media_name is required")

        headers = {
            "Accept": "*/*",
            "Referer": (
                f"https://labs.google/fx/zh/tools/flow/project/{project_id}"
                if str(project_id or "").strip()
                else "https://labs.google/fx/zh/tools/flow"
            ),
            "sec-fetch-dest": "image",
            "sec-fetch-mode": "no-cors",
            "sec-fetch-site": "same-origin",
        }
        if st:
            headers["Cookie"] = f"__Secure-next-auth.session-token={st}"

        account_id = st[:16] if st else None
        headers["User-Agent"] = self._generate_user_agent(account_id)
        for key, value in self._default_client_headers.items():
            headers.setdefault(key, value)

        url = self._build_media_redirect_url(clean_media_name)
        proxy_url = None
        if self.proxy_manager:
            if hasattr(self.proxy_manager, "get_media_proxy_url"):
                proxy_url = await self.proxy_manager.get_media_proxy_url()
            elif hasattr(self.proxy_manager, "get_request_proxy_url"):
                proxy_url = await self.proxy_manager.get_request_proxy_url()
            else:
                proxy_url = await self.proxy_manager.get_proxy_url()

        try:
            async with AsyncSession(trust_env=False) as session:
                response = await session.get(
                    url,
                    headers=headers,
                    proxy=proxy_url,
                    timeout=self._get_control_plane_timeout(),
                    impersonate="chrome124",
                    allow_redirects=False,
                )
            location = str(response.headers.get("location") or "").strip()
            if response.status_code in {301, 302, 303, 307, 308} and location:
                return location
            if response.status_code == 200 and location:
                return location
            raise RuntimeError(
                f"media redirect unresolved: status={response.status_code}, body={response.text[:200]}"
            )
        except Exception as exc:
            if httpx is None:
                raise RuntimeError(f"media redirect resolve failed: {exc}") from exc

            try:
                async with httpx.AsyncClient(
                    follow_redirects=False,
                    proxy=proxy_url,
                    trust_env=False,
                    timeout=self._get_control_plane_timeout(),
                    verify=False,
                ) as client:
                    response = await client.get(url, headers=headers)
                location = str(response.headers.get("location") or "").strip()
                if response.status_code in {301, 302, 303, 307, 308} and location:
                    return location
                raise RuntimeError(
                    f"media redirect unresolved: status={response.status_code}, body={response.text[:200]}"
                )
            except Exception as fallback_exc:
                raise RuntimeError(f"media redirect resolve failed: {fallback_exc}") from fallback_exc

