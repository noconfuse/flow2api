    def _detect_image_mime_type(self, image_bytes: bytes) -> str:
        """通过文件头 magic bytes 检测图片 MIME 类型

        Args:
            image_bytes: 图片字节数据

        Returns:
            MIME 类型字符串，默认 image/jpeg
        """
        if len(image_bytes) < 12:
            return "image/jpeg"

        # WebP: RIFF....WEBP
        if image_bytes[:4] == b'RIFF' and image_bytes[8:12] == b'WEBP':
            return "image/webp"
        # PNG: 89 50 4E 47
        if image_bytes[:4] == b'\x89PNG':
            return "image/png"
        # JPEG: FF D8 FF
        if image_bytes[:3] == b'\xff\xd8\xff':
            return "image/jpeg"
        # GIF: GIF87a 或 GIF89a
        if image_bytes[:6] in (b'GIF87a', b'GIF89a'):
            return "image/gif"
        # BMP: BM
        if image_bytes[:2] == b'BM':
            return "image/bmp"
        # JPEG 2000: 00 00 00 0C 6A 50
        if image_bytes[:6] == b'\x00\x00\x00\x0cjP':
            return "image/jp2"

        return "image/jpeg"

    def _convert_to_jpeg(self, image_bytes: bytes) -> bytes:
        """将图片转换为 JPEG 格式

        Args:
            image_bytes: 原始图片字节数据

        Returns:
            JPEG 格式的图片字节数据
        """
        from io import BytesIO
        from PIL import Image

        img = Image.open(BytesIO(image_bytes))
        # 如果有透明通道，转换为 RGB
        if img.mode in ('RGBA', 'LA', 'P'):
            img = img.convert('RGB')
        
        output = BytesIO()
        img.save(output, format='JPEG', quality=95)
        return output.getvalue()

    def _detect_video_mime_type(
        self,
        video_bytes: bytes,
        *,
        file_name: Optional[str] = None,
        declared_mime_type: Optional[str] = None,
    ) -> str:
        normalized_declared = str(declared_mime_type or "").strip().lower()
        if normalized_declared.startswith("video/"):
            return normalized_declared

        normalized_file_name = str(file_name or "").strip()
        guessed_mime_type, _encoding = mimetypes.guess_type(normalized_file_name)
        if isinstance(guessed_mime_type, str) and guessed_mime_type.startswith("video/"):
            return guessed_mime_type

        if video_bytes[:12].startswith(b"\x00\x00\x00") and b"ftyp" in video_bytes[:16]:
            brand = video_bytes[8:12]
            if brand in {b"qt  "}:
                return "video/quicktime"
            return "video/mp4"
        if video_bytes[:4] == b"\x1a\x45\xdf\xa3":
            return "video/webm"
        if video_bytes[:4] == b"RIFF" and video_bytes[8:12] == b"AVI ":
            return "video/x-msvideo"

        return "application/octet-stream"

    def _build_safe_upload_file_name(self, file_name: str, *, fallback_prefix: str = "upload") -> str:
        normalized_name = str(file_name or "").strip()
        base_name = os.path.basename(normalized_name) or f"{fallback_prefix}.bin"
        raw_stem, raw_ext = os.path.splitext(base_name)
        ext_ascii = unicodedata.normalize("NFKD", raw_ext).encode("ascii", "ignore").decode("ascii")
        ext_ascii = re.sub(r"[^A-Za-z0-9.]+", "", ext_ascii)
        if ext_ascii and not ext_ascii.startswith("."):
            ext_ascii = f".{ext_ascii}"

        stem_ascii = unicodedata.normalize("NFKD", raw_stem).encode("ascii", "ignore").decode("ascii")
        stem_ascii = re.sub(r"[^A-Za-z0-9._-]+", "-", stem_ascii).strip("._-")
        if not stem_ascii:
            stem_ascii = f"{fallback_prefix}-{int(time.time())}"
        return f"{stem_ascii}{ext_ascii or '.bin'}"

    @staticmethod
    def _extract_response_header_value(headers: Any, *header_names: str) -> str:
        if not isinstance(headers, dict):
            return ""
        normalized_headers = {
            str(key or "").strip().lower(): str(value or "").strip()
            for key, value in headers.items()
            if str(key or "").strip()
        }
        for header_name in header_names:
            value = normalized_headers.get(str(header_name or "").strip().lower(), "")
            if value:
                return value
        return ""

    def _extract_upload_session_url(self, result: Dict[str, Any]) -> str:
        response_headers = result.get("response_headers") if isinstance(result, dict) else {}
        for header_name in ("x-upload-session-url", "x-goog-upload-url", "location"):
            value = self._extract_response_header_value(response_headers, header_name)
            if value:
                return value

        def _walk(value: Any) -> str:
            if isinstance(value, str):
                stripped = value.strip()
                if stripped.startswith("https://") and "upload_protocol=resumable" in stripped:
                    return stripped
                try:
                    return _walk(json.loads(stripped))
                except Exception:
                    return ""
            if isinstance(value, dict):
                for key in (
                    "uploadSessionUrl",
                    "upload_session_url",
                    "sessionUrl",
                    "session_url",
                    "xUploadSessionUrl",
                ):
                    candidate = value.get(key)
                    if isinstance(candidate, str) and candidate.strip():
                        return candidate.strip()
                for nested_value in value.values():
                    candidate = _walk(nested_value)
                    if candidate:
                        return candidate
            if isinstance(value, list):
                for item in value:
                    candidate = _walk(item)
                    if candidate:
                        return candidate
            return ""

        for candidate_root in (
            result.get("response") if isinstance(result, dict) else None,
            result.get("text") if isinstance(result, dict) else None,
        ):
            candidate = _walk(candidate_root)
            if candidate:
                return candidate
        return ""

