    def _looks_like_media_entry(self, value: Any) -> bool:
        if not isinstance(value, dict):
            return False
        if not (
            value.get("mediaMetadata")
            or value.get("mediaType")
            or value.get("video")
            or value.get("image")
            or value.get("audio")
        ):
            return False
        if value.get("projectContents"):
            return False
        if value.get("name") and any(
            key in value for key in ("createTime", "updateTime", "sceneId", "workflowStepId")
        ):
            return True
        return bool(value.get("video") or value.get("image") or value.get("audio") or value.get("mediaType"))

    def _unwrap_media_entry(self, media: Dict[str, Any]) -> Dict[str, Any]:
        """兼容 externalReferenceMedia 这类 {mediaId, mediaType, media:{...}} 包装对象。"""
        inner_media = media.get("media") if isinstance(media.get("media"), dict) else None
        if not inner_media:
            return media

        merged = dict(inner_media)
        if media.get("mediaId") and not merged.get("name"):
            merged["name"] = media.get("mediaId")
        if media.get("mediaType") and not merged.get("mediaType"):
            merged["mediaType"] = media.get("mediaType")
        if media.get("workflowDisplayName") and not merged.get("workflowDisplayName"):
            merged["workflowDisplayName"] = media.get("workflowDisplayName")
        return merged

    def _dedupe_media_entries_preserve_order(self, items: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        deduped: List[Dict[str, Any]] = []
        seen_keys: set[str] = set()
        for item in items:
            normalized_item = self._unwrap_media_entry(item)
            name = str(normalized_item.get("name") or "").strip()
            project_id = str(normalized_item.get("projectId") or "").strip()
            dedupe_key = f"{project_id}:{name}" if (project_id or name) else ""
            if dedupe_key and dedupe_key in seen_keys:
                continue
            if dedupe_key:
                seen_keys.add(dedupe_key)
            deduped.append(normalized_item)
        return deduped

    def _extract_ordered_project_media_entries(self, value: Any) -> List[Dict[str, Any]]:
        """优先读取 projectInitialData 中官方返回的媒体数组，保持上游顺序。"""
        if not isinstance(value, dict):
            return []

        candidate_lists: List[Any] = []
        if isinstance(value.get("media"), list):
            candidate_lists.append(value.get("media"))

        project_contents = value.get("projectContents") if isinstance(value.get("projectContents"), dict) else None
        if isinstance(project_contents, dict):
            for key in ("media", "projectMedia", "mediaEntries", "assets"):
                candidate = project_contents.get(key)
                if isinstance(candidate, list):
                    candidate_lists.append(candidate)

        for candidate_list in candidate_lists:
            ordered_items: List[Dict[str, Any]] = []
            for item in candidate_list:
                if not isinstance(item, dict):
                    continue
                normalized_item = self._unwrap_media_entry(item)
                if self._looks_like_media_entry(item) or self._looks_like_media_entry(normalized_item):
                    ordered_items.append(item)
            if ordered_items:
                return self._dedupe_media_entries_preserve_order(ordered_items)
        return []

    def _collect_media_entries(self, value: Any) -> List[Dict[str, Any]]:
        """从 projectInitialData 的嵌套结构中递归提取媒体对象。"""
        collected: List[Dict[str, Any]] = []

        def walk(node: Any):
            if isinstance(node, dict):
                if self._looks_like_media_entry(node):
                    collected.append(node)
                for child in node.values():
                    walk(child)
            elif isinstance(node, list):
                for item in node:
                    walk(item)

        walk(value)
        return self._dedupe_media_entries_preserve_order(collected)

    def _normalize_upstream_media_item(self, media: Dict[str, Any]) -> Dict[str, Any]:
        """将上游媒体对象整理成前端更容易消费的结构。"""
